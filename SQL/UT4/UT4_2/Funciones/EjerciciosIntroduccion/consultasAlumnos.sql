--Mostrar el nombre en mayúsculas y el dominio del email:
SELECT UPPER(NOMBRE) NOMBRE, SUBSTR(EMAIL,INSTR(EMAIL,'@')+1)
FROM USUARIOS;

--Listar usuarios cuyo email no termina en .com.
SELECT UPPER(NOMBRE) AS NOMBRE, SUBSTR(EMAIL,INSTR(EMAIL,'@')+1) AS MAIL
FROM USUARIOS
WHERE SUBSTR(EMAIL,INSTR(EMAIL,'.')) != '.com';

SELECT NOMBRE, EMAIL
FROM USUARIOS U
WHERE NOT EXISTS (SELECT EMAIL
                    FROM USUARIOS
                    WHERE UPPER(EMAIL) LIKE '%.COM' AND U.EMAIL = EMAIL);

SELECT NOMBRE, EMAIL
FROM USUARIOS U
WHERE EMAIL NOT LIKE'%.COM';

--Mostrar nombre, fecha de alta y:
    --año de alta
    --mes de alta
SELECT NOMBRE, FECHA_ALTA, EXTRACT(YEAR FROM FECHA_ALTA) AÑO, EXTRACT(MONTH FROM FECHA_ALTA) MES
FROM USUARIOS;

--Mostrar los usuarios que llevan más de 2 años registrados.
SELECT NOMBRE, ROUND(MONTHS_BETWEEN(SYSDATE,FECHA_ALTA)/12) AS AÑOS_REGISTRADOS
FROM USUARIOS
WHERE MONTHS_BETWEEN(SYSDATE, FECHA_ALTA) > 24;

--Mostrar cada pedido con:

    --importe original
    --importe redondeado a 2 decimales
    --importe truncado
SELECT IMPORTE AS IMPORTE_ORIGINAL, ROUND(IMPORTE,2) AS IMPORTE_REDONDEADO,TRUNC(IMPORTE) AS IMPORTE_TRUNCADO
FROM PEDIDOS
WHERE IMPORTE IS NOT NULL;

--Mostrar el importe con formato moneda:
SELECT TO_CHAR(IMPORTE, '999G999D999L') AS IMPORTE_MONEDA
FROM PEDIDOS;

--Mostrar todos los usuarios, tengan o no pedidos:
    --Si no tienen pedidos → mostrar "SIN PEDIDOS"
SELECT NOMBRE, NVL(TO_CHAR(ID_PEDIDO), 'SIN PEDIDOS')
FROM USUARIOS U LEFT JOIN PEDIDOS P ON U.ID_USUARIO = P.ID_USUARIO;

SELECT NOMBRE,
CASE
    WHEN ID_PEDIDO IS NULL THEN 'SIN PEDIDOS'
    ELSE TO_CHAR(ID_PEDIDO)
    END AS ID_PEDIDO
FROM USUARIOS U LEFT JOIN PEDIDOS P ON U.ID_USUARIO = P.ID_USUARIO;

