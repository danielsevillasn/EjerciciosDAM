--Mostrar los usuarios que han realizado algún pedido con importe mayor que la media individual de sus pedidos
SELECT DISTINCT U.ID_USUARIO, U.NOMBRE
FROM USUARIOS U
JOIN PEDIDOS P ON P.ID_USUARIO = U.ID_USUARIO
WHERE P.IMPORTE > (
    SELECT AVG(P2.IMPORTE)
    FROM PEDIDOS P2
    WHERE P2.ID_USUARIO = P.ID_USUARIO
);

