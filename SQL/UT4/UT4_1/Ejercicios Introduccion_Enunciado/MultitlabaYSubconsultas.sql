SELECT T.NOMBRE_TRAB, T.SALARIO_MIN, T.SALARIO_MAX, HL.FECHA_INICIO, HL.FECHA_FIN
FROM HISTORIAL_LABORAL HL, TRABAJOS T
WHERE HL.TRAB_COD = T.TRABAJO_COD AND HL.EMPLEADO_DNI = 12345;