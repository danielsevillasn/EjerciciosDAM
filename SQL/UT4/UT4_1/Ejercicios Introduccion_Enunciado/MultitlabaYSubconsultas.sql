SELECT E.NOMBRE, E.APELLIDO1, HS.SALARIO, HS.FECHA_COMIENZO
FROM EMPLEADOS E, HISTORIAL_SALARIAL HS
WHERE E.DNI = HS.EMPLEADO_DNI
ORDER BY E.NOMBRE, HS.FECHA_COMIENZO;

