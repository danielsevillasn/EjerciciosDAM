CREATE VIEW V_ALUMNOS_APROBADOS_RA
AS
SELECT A.ID_ALUMNO, A.NOMBRE || ' ' || A.APELLIDOS AS ALUMNO, RA.ID_RA AS ID_RA, RA.CODIGO AS RA_CODIGO, C.NOTA
FROM CALIFICACIONES C JOIN ALUMNOS A ON C.ID_ALUMNO = A.ID_ALUMNO
JOIN RESULTADOS_APRENDIZAJE RA ON C.ID_RA = RA.ID_RA
WHERE C.NOTA >5;