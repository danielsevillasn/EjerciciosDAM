CREATE TABLE LIBROS(
    ID_Libro NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Titulo VARCHAR2(100) NOT NULL,
    Genero VARCHAR2(50),
    Fecha_Publicacion DATE,
    ID_Autor NUMBER NOT NULL
);

CREATE TABLE PRESTAMOS(
    ID_Prestamo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Libro NUMBER NOT NULL,
    Fecha_Prestamo DATE DEFAULT SYSDATE,
    Fecha_Devolucion DATE,
    Usuario NUMBER NOT NULL
);

CREATE TABLE AUTORES(
    ID_Autor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR2(100) NOT NULL,
    Nacionalidad VARCHAR2(50)
);

CREATE TABLE USUARIOS(
    ID_Usuario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre VARCHAR2(100) NOT NULL,
    Apellido VARCHAR2(100) NOT NULL,
    Fecha_Nacimiento DATE,
    Fecha_Alta DATE,
    CONSTRAINT Fecha_Alta CHECK (Fecha_Alta > Fecha_Nacimiento)    
);

ALTER TABLE LIBROS
ADD CONSTRAINT LIB_IDA_FK FOREIGN KEY (ID_Autor) REFERENCES AUTORES(ID_Autor) ON DELETE CASCADE;

ALTER TABLE PRESTAMOS
ADD CONSTRAINT PRE_USU_FK FOREIGN KEY (Usuario) REFERENCES USUARIOS(ID_Usuario) ON DELETE CASCADE;  

ALTER TABLE PRESTAMOS
ADD CONSTRAINT PRE_IDL_FK FOREIGN KEY (ID_Libro) REFERENCES LIBROS(ID_Libro) ON DELETE CASCADE;

