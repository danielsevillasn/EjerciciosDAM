DROP TABLE ASIENTOS CASCADE CONSTRAINTS;
DROP TABLE REPRESENTACIONES CASCADE CONSTRAINTS;
DROP TABLE ENTRADAS CASCADE CONSTRAINTS;
DROP TABLE ESPECTADORES CASCADE CONSTRAINTS;

CREATE TABLE ESPECTACULOS (
    COD_ESPECTACULO VARCHAR2(4),
    NOMBRE VARCHAR2(200),
    TIPO VARCHAR2(100),
    FECHA_INICIAL DATE,
    FECHA_FINAL DATE,
    INTERPRETE VARCHAR2(100),
    COD_RECINTO VARCHAR2(4),
    CONSTRAINT ESPECTACULOS_COD_PK PRIMARY KEY (COD_ESPECTACULO),
    CONSTRAINT ESPECTACULOS_FECHAS_CH CHECK(FECHA_FINAL > FECHA_INICIAL)
);

CREATE TABLE PRECIOS_ESPECTACULOS(
    COD_ESPECTACULO VARCHAR2(4),
    COD_RECINTO VARCHAR2(4),
    ZONA VARCHAR2(4),
    PRECIO NUMBER(5,2),
    CONSTRAINT PRECIOESPEC_COD_PK PRIMARY KEY (COD_ESPECTACULO, COD_RECINTO, ZONA)
);

CREATE TABLE RECINTOS (
    COD_RECINTO VARCHAR2(4), 
    NOMBRE VARCHAR2(100), 
    DIRECCION VARCHAR2(200), 
    CIUDAD VARCHAR2(200), 
    TELEFONO NUMBER(9), 
    HORARIO VARCHAR2(50),
    CONSTRAINT RECINTOS_COD_PK PRIMARY KEY (COD_RECINTO)
);

ALTER TABLE ESPECTACULOS
    ADD CONSTRAINT ESPECT_RECINTO_FK FOREIGN KEY (COD_RECINTO) REFERENCES RECINTOS;

CREATE TABLE ZONAS_RECINTOS(
    COD_RECINTO VARCHAR2(4), 
    ZONA VARCHAR2(4), 
    CAPACIDAD NUMBER(4),
    CONSTRAINT ZONASRECINTOS_COD_PK PRIMARY KEY(COD_RECINTO, ZONA),
    CONSTRAINT ZONASRECINTOS_RECINTO_FK FOREIGN KEY (COD_RECINTO) REFERENCES RECINTOS
);
