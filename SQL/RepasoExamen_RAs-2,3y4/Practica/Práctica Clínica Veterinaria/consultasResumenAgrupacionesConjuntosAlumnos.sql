--25.Mascotas que no tienen pago asociado. 
--¿Podrías hacer la consulta de tal forma que supiéramos el nombre de la mascota y de su cliente?
SELECT C.NOMBRE  AS CLIENTE,
       M.NOMBRE  AS MASCOTA,
       M.ESPECIE
FROM MASCOTAS M
JOIN CLIENTES C
  ON M.ID_CLIENTE = C.ID_CLIENTE
LEFT JOIN CITAS CI
  ON M.ID_CLIENTE = CI.ID_CLIENTE
 AND M.ID_MASCOTA = CI.ID_MASCOTA
LEFT JOIN PAGOS P
  ON CI.ID_CLIENTE = P.ID_CLIENTE
 AND CI.ID_MASCOTA = P.ID_MASCOTA
 AND CI.FECHA_CITA = P.FECHA_CITA
WHERE CI.ID_MASCOTA IS NULL
   OR P.ID_CLIENTE  IS NULL;

--26.Para cada cliente, mostrar:
--número de mascotas
--número de citas
--importe total pagado
SELECT
    C.ID_CLIENTE,
    C.NOMBRE,
    (SELECT COUNT(*)
     FROM MASCOTAS M
     WHERE M.ID_CLIENTE = C.ID_CLIENTE)       AS NUM_MASCOTAS,
    (SELECT COUNT(*)
     FROM CITAS CI
     WHERE CI.ID_CLIENTE = C.ID_CLIENTE)      AS NUM_CITAS,
    (SELECT NVL(SUM(P.IMPORTE), 0)
     FROM PAGOS P
     WHERE P.ID_CLIENTE = C.ID_CLIENTE)       AS IMPORTE_TOTAL
FROM CLIENTES C
ORDER BY C.ID_CLIENTE;

--27.Mostrar la mascota con mayor gasto acumulado.
SELECT M.NOMBRE
FROM MASCOTAS M JOIN PAGOS P ON M.ID_CLIENTE = P.ID_CLIENTE AND M.ID_MASCOTA = P.ID_MASCOTA
GROUP BY M.NOMBRE HAVING SUM(IMPORTE) = (SELECT MAX(SUM(IMPORTE)) 
                                        FROM PAGOS 
                                        GROUP BY ID_CLIENTE, ID_MASCOTA);

--28.Mostrar el cliente con más citas.
SELECT CLI.NOMBRE
FROM CITAS C JOIN CLIENTES CLI ON C.ID_CLIENTE = CLI.ID_CLIENTE
GROUP BY CLI.NOMBRE 
HAVING COUNT(*) = (
    SELECT MAX(CONT(*))
    FROM CITAS
    GROUP BY ID_CLIENTE
);

--29.Mostrar qué veterinario ha realizado más atenciones.
SELECT P.NOMBRE
FROM PERSONAL P JOIN ATENCIONES A ON P.ID_CLIENTE = A.ID_CLIENTE
GROUP BY P.NOMBRE
HAVING COUNT(*) = (
    SELECT MAX(CONT(*))
    FROM ATENCIONES
    GROUP BY ID_PERSONAL
);

