--26.Para cada cliente, mostrar:
--número de mascotas
--número de citas
--importe total pagado
SELECT CLI.ID_CLIENTE, COUNT(DISTINCT M.ID_MASCOTA) AS NUMERO_MASCOTAS, COUNT(DISTINCT C.FECHA_CITA) AS NUMERO_CITAS,
NVL(SUM(P.IMPORTE),0) AS TOTAL_PAGADO
FROM CLIENTES CLI LEFT JOIN MASCOTAS M ON CLI.ID_CLIENTE = M.ID_CLIENTE LEFT JOIN CITAS C ON C.ID_CLIENTE = CLI.ID_CLIENTE
GROUP BY C.ID_CLIENTE;

--27.Mostrar la mascota con mayor gasto acumulado.
SELECT M.NOMBRE
FROM MASCOTAS M JOIN PAGOS P ON M.ID_CLIENTE = P.ID_CLIENTE AND M.ID_MASCOTA = P.ID_MASCOTA
GROUP BY M.NOMBRE HAVING SUM(IMPORTE) = (SELECT MAX(SUM(IMPORTE)) 
                                        FROM PAGOS 
                                        GROUP BY ID_CLIENTE, ID_MASCOTA);

--28.Mostrar el cliente con más citas.
SELECT CLI.NOMBRE
FROM CITAS C JOIN CLIENTES CLI ON C.ID_CLIENTE = CLI.ID_CLIENTE
GROUP BY CLI.NOMBRE 
HAVING COUNT(*) = (
    SELECT MAX(CONT(*))
    FROM CITAS
    GROUP BY ID_CLIENTE
);

--29.Mostrar qué veterinario ha realizado más atenciones.
