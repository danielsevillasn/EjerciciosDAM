public class OperadoresAritmeticos {
    public static void main(String[] args){
        int x; //El int sirve para establecer una variable en su forma entera
        x = 5; //Le agrega un valor a la variable
        char y = 'a'; //El char sirve para establecer un caracter 
        char z = 'b'; //El char sirve para establecer un caracter 
        System.out.println(x + " " + (x +5) + " "  + (x-5)); //Muestra por pantalla las operaciones de suma y resta ya realizadas
        System.out.println((x*5) + " " + (x/5) + " " + (x%3)); //Muestra por pantalla las operaciones de multiplicación, de división normal y el resto de la division ya realizadas
        System.out.println(y+z); //Suma los valores que estan en la tablita de ASCII
    }
}