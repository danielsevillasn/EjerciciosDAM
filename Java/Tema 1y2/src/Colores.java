public class Colores {
    public static void main(String[] args) {
        System.out.print("\033[33m mandarina"); //El 033[33m establece el formato a color y el respecitvo tipo de color con el 33m
        System.out.print("\033[32m hierba"); //Los colores estan en una tabla
        System.out.print("\033[31m tomate");
        System.out.print("\033[37m sabanas");
        System.out.print("\033[36m cielo");
        System.out.print("\033[35m nazareno");
        System.out.print("\033[34m mar");
    }
}
