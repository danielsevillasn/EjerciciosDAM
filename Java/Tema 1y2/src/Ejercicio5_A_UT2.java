public class Ejercicio5_A_UT2 {
    public static void main(String[] args) throws Exception {
        int x; //El int sirve para establecer una variable en su forma entera
        x = 5; //Le agrega un valor a la variable
        System.out.println("El valor de x es " +x); //ln es para poner un enter
        long y; //El long sirve para cuando quieres establecer un numero entero que sea muy largo
        y = 1918381904;
        System.out.println("El valor de y es " + y); 
        char z; //El char sirve para cuando quieres establecer un carácter suelto 
        z = 'a'; //En la variable char se han de utilizar la ''
        System.out.println("El valor de z es " + z); 
        boolean a; //El boolean sirve para cuando quieres establecer falso o verdadero 
        a = true;
        System.out.println("El valor de a es " + a); 
        double b; //El double sirve para establecer un numero decimal
        b = 24.56;
        System.out.println("El valor de b es " + b); 
        String c; //El String sirve para establecer una cadena de todo tipo de caracteres, desde numeros hasta letras y simbolos
        c = "Hey muy buenas a todos 777"; //En la variable string se han de utilizar las ""
        System.out.println("El valor de c es " + c); 
    }

}
