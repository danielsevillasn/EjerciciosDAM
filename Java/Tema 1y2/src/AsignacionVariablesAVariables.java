public class AsignacionVariablesAVariables {
    public static void main(String[] args){
        int x = 5; //El int sirve para establecer una variable en su forma entera
        int y = 10; //El int sirve para establecer una variable en su forma entera
        int sum = x+y;
        int rest = x-y;
        int mul = x*y;
        int div = x/y;
        System.out.println("la suma de mis variables es " +sum); //Muestra por pantalla la suma
        System.out.println("la resta de mis variables es " +rest); //Muestra por pantalla la resta
        System.out.println("la multiplicación de mis variables es " +mul); //Muestra por pantalla la multiplicación
        System.out.println("la división de mis variables es " +div); //Muestra por pantalla la división
    }
}
